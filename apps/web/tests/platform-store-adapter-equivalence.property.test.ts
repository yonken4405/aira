/**
 * @vitest-environment node
 *
 * Property 13: Store adapter equivalence — in-memory store invariants.
 *
 * // Feature: tenant-responder-network, Property 13: Store adapter equivalence
 *
 * Drives the in-memory `PlatformStore` (`createMemoryPlatformStore`) as the
 * oracle for the behaviour that BOTH the Postgres and in-memory adapters must
 * satisfy (R9.8). We cannot run real Postgres in tests, so we use the in-memory
 * store as the model: a property is useful here precisely because its
 * *self-consistency* invariants are the same invariants any conforming adapter
 * must preserve.
 *
 * Random sequences of agency/capability operations are generated by fast-check
 * (≥ 100 iterations, one isolated store instance per iteration). Six invariants
 * are checked on every iteration:
 *
 *   1. After `createAgency` succeeds, `findAgencyById(id)` returns the same record.
 *   2. After `renameAgency`, `findAgencyById` returns the updated name/code.
 *   3. After `setAgencyActive(id, false)`, `findAgencyById` still finds the row
 *      with `active: false`.
 *   4. After `setCapabilityForCategory(tenant, cat, types)`,
 *      `readCapabilityConfig(tenant)[cat]` equals the de-duplicated submitted set.
 *   5. `readCapabilityConfig` never throws and always returns a value for all 4
 *      frozen categories (after at least one `setCapabilityForCategory` call).
 *   6. Roundtrip: `createAgency` then `findAgencyById(id)` returns the exact same
 *      record.
 *
 * Validates: Requirements 9.8
 */

import fc from 'fast-check';
import { describe, expect, it } from 'vitest';

import type { AgencyType } from '@aira/ui';
import { AGENCY_TYPES } from '@aira/ui';

import { createMemoryPlatformStore } from './support/memory-platform-store';

const RUNS = 100;

// ─────────────────────────────────────────────────────────────────────────────
// Arbitraries
// ─────────────────────────────────────────────────────────────────────────────

/** A non-empty tenant name. */
const tenantNameArb: fc.Arbitrary<string> = fc
  .string({ minLength: 2, maxLength: 40 })
  .filter((s) => s.trim().length >= 2);

/** An agency name (trimmed 2..64 chars). */
const agencyNameArb: fc.Arbitrary<string> = fc
  .string({ minLength: 2, maxLength: 64 })
  .filter((s) => s.trim().length >= 2 && s.trim().length <= 64);

/** An agency code (trimmed 2..12 chars). */
const agencyCodeArb: fc.Arbitrary<string> = fc
  .string({ minLength: 2, maxLength: 12 })
  .filter((s) => s.trim().length >= 2 && s.trim().length <= 12);

/** One of the five valid agency types. */
const agencyTypeArb: fc.Arbitrary<AgencyType> = fc.constantFrom<AgencyType>(...AGENCY_TYPES);

// ─────────────────────────────────────────────────────────────────────────────
// Property 13 — store adapter equivalence invariants
// ─────────────────────────────────────────────────────────────────────────────

describe('Property 13: Store adapter equivalence', () => {
  /**
   * Invariant 1 + 6 (combined): After `createAgency` succeeds,
   * `findAgencyById(id)` returns the exact same record as the create result
   * (roundtrip equivalence).
   *
   * Validates: R9.8
   */
  it('Inv 1+6: createAgency success → findAgencyById returns the same record', async () => {
    await fc.assert(
      fc.asyncProperty(
        tenantNameArb,
        agencyNameArb,
        agencyCodeArb,
        agencyTypeArb,
        async (tenantName, agencyName, agencyCode, agencyType) => {
          const store = createMemoryPlatformStore();

          // Seed a tenant so createAgency can succeed
          const tenant = await store.createTenantWithLgu({
            name: tenantName,
            region: 'Region VII',
            province: 'Cebu',
            lguName: `${tenantName} LGU`,
            lat: null,
            lon: null,
            now: 1_700_000_000_000,
          });

          const result = await store.createAgency({
            tenantId: tenant.id,
            name: agencyName,
            code: agencyCode,
            agencyType,
          });

          // Should succeed (unique name/code within a fresh store)
          expect(result.status).toBe('ok');
          if (result.status !== 'ok') return;

          const created = result.agency;

          // Invariant 1: findAgencyById returns a record
          const found = await store.findAgencyById(created.id);
          expect(found).not.toBeNull();
          if (found === null) return;

          // Invariant 6: roundtrip — exact same record
          expect(found.id).toBe(created.id);
          expect(found.tenantId).toBe(created.tenantId);
          expect(found.name).toBe(created.name);
          expect(found.code).toBe(created.code);
          expect(found.agencyType).toBe(created.agencyType);
          expect(found.active).toBe(created.active);
        },
      ),
      { numRuns: RUNS },
    );
  });

  /**
   * Invariant 2: After `renameAgency`, `findAgencyById` returns the row with
   * updated name and code.
   *
   * Validates: R9.8
   */
  it('Inv 2: renameAgency → findAgencyById returns updated name/code', async () => {
    await fc.assert(
      fc.asyncProperty(
        tenantNameArb,
        agencyNameArb,
        agencyCodeArb,
        agencyTypeArb,
        // New name and code must differ from originals to avoid false positives
        agencyNameArb,
        agencyCodeArb,
        async (tenantName, origName, origCode, agencyType, newName, newCode) => {
          // If the renamed values collide with originals (case-insensitively), skip
          if (origName.trim().toLowerCase() === newName.trim().toLowerCase()) return;
          if (origCode.trim().toLowerCase() === newCode.trim().toLowerCase()) return;

          const store = createMemoryPlatformStore();

          const tenant = await store.createTenantWithLgu({
            name: tenantName,
            region: 'Region VII',
            province: 'Cebu',
            lguName: `${tenantName} LGU`,
            lat: null,
            lon: null,
            now: 1_700_000_000_000,
          });

          const result = await store.createAgency({
            tenantId: tenant.id,
            name: origName,
            code: origCode,
            agencyType,
          });

          if (result.status !== 'ok') return; // skip if dup (rare but possible)

          const agencyId = result.agency.id;

          // Rename to the new name/code
          let renamed: Awaited<ReturnType<typeof store.renameAgency>>;
          try {
            renamed = await store.renameAgency(agencyId, {
              name: newName.trim(),
              code: newCode.trim(),
            });
          } catch {
            // Collision with another agency in the tenant — skip this case
            return;
          }

          expect(renamed).not.toBeNull();
          if (renamed === null) return;

          // Read back
          const found = await store.findAgencyById(agencyId);
          expect(found).not.toBeNull();
          if (found === null) return;

          expect(found.name).toBe(newName.trim());
          expect(found.code).toBe(newCode.trim());
          // Other fields must be preserved
          expect(found.id).toBe(agencyId);
          expect(found.tenantId).toBe(tenant.id);
          expect(found.agencyType).toBe(agencyType);
        },
      ),
      { numRuns: RUNS },
    );
  });

  /**
   * Invariant 3: After `setAgencyActive(id, false)`, `findAgencyById` still
   * finds the row and it has `active: false`.
   *
   * Validates: R9.8
   */
  it('Inv 3: setAgencyActive(false) → row still exists with active: false', async () => {
    await fc.assert(
      fc.asyncProperty(
        tenantNameArb,
        agencyNameArb,
        agencyCodeArb,
        agencyTypeArb,
        async (tenantName, agencyName, agencyCode, agencyType) => {
          const store = createMemoryPlatformStore();

          const tenant = await store.createTenantWithLgu({
            name: tenantName,
            region: 'Region VII',
            province: 'Cebu',
            lguName: `${tenantName} LGU`,
            lat: null,
            lon: null,
            now: 1_700_000_000_000,
          });

          const result = await store.createAgency({
            tenantId: tenant.id,
            name: agencyName,
            code: agencyCode,
            agencyType,
          });

          if (result.status !== 'ok') return;

          const agencyId = result.agency.id;

          const deactivated = await store.setAgencyActive(agencyId, false);
          expect(deactivated).not.toBeNull();
          if (deactivated === null) return;

          // Row must still be findable
          const found = await store.findAgencyById(agencyId);
          expect(found).not.toBeNull();
          if (found === null) return;

          expect(found.active).toBe(false);
          // Other fields unchanged
          expect(found.id).toBe(agencyId);
          expect(found.agencyType).toBe(agencyType);
        },
      ),
      { numRuns: RUNS },
    );
  });

  /**
   * Invariant 4: agency coverage round-trips through the store — after
   * `setCoverage(agency, offices)`, `listCoverage(agency)` returns the de-duplicated
   * set and `coversOffice` agrees (single-lgu-agency-network R5).
   */
  it('Inv 4: setCoverage → listCoverage/coversOffice are self-consistent (de-duplicated)', async () => {
    await fc.assert(
      fc.asyncProperty(
        tenantNameArb,
        fc.array(fc.string({ minLength: 1, maxLength: 12 }), { minLength: 0, maxLength: 6 }),
        async (tenantName, officeIds) => {
          const store = createMemoryPlatformStore();
          const tenant = await store.createTenantWithLgu({
            name: tenantName,
            region: 'Region VII',
            province: 'Cebu',
            lguName: `${tenantName} LGU`,
            lat: null,
            lon: null,
            now: 1_700_000_000_000,
          });
          const created = await store.createAgency({
            tenantId: tenant.id,
            name: 'Coverage Agency',
            code: 'COV',
            agencyType: 'FIRE',
          });
          if (created.status !== 'ok') return;
          const agencyId = created.agency.id;

          await store.setCoverage(agencyId, officeIds);

          const expected = new Set(officeIds);
          const actual = new Set(await store.listCoverage(agencyId));
          expect(actual).toEqual(expected);
          for (const officeId of expected) {
            expect(await store.coversOffice(agencyId, officeId)).toBe(true);
          }
        },
      ),
      { numRuns: RUNS },
    );
  });

  /**
   * Composite: multi-op sequence — create, rename, activate/deactivate,
   * capability set — all self-consistent.
   *
   * Exercises the store under a random sequence of operations to stress-test
   * combined invariants 1–6.
   *
   * Validates: R9.8
   */
  it('Composite: random op sequence preserves all store invariants', async () => {
    await fc.assert(
      fc.asyncProperty(
        tenantNameArb,
        fc.array(
          fc.record({
            name: agencyNameArb,
            code: agencyCodeArb,
            agencyType: agencyTypeArb,
          }),
          { minLength: 1, maxLength: 5 },
        ),
        fc.array(fc.string({ minLength: 1, maxLength: 12 }), { minLength: 0, maxLength: 4 }),
        fc.boolean(), // whether to deactivate the first agency
        async (tenantName, agencies, coverageOffices, deactivateFirst) => {
          const store = createMemoryPlatformStore();

          const tenant = await store.createTenantWithLgu({
            name: tenantName,
            region: 'Region VII',
            province: 'Cebu',
            lguName: `${tenantName} LGU`,
            lat: null,
            lon: null,
            now: 1_700_000_000_000,
          });

          const createdIds: string[] = [];

          for (const input of agencies) {
            let result: Awaited<ReturnType<typeof store.createAgency>>;
            try {
              result = await store.createAgency({
                tenantId: tenant.id,
                name: input.name,
                code: input.code,
                agencyType: input.agencyType,
              });
            } catch {
              // Per-tenant dup — skip this input
              continue;
            }

            if (result.status !== 'ok') continue;

            const id = result.agency.id;
            createdIds.push(id);

            // Inv 1+6: findAgencyById immediately after create
            const found = await store.findAgencyById(id);
            expect(found).not.toBeNull();
            if (found === null) return;
            expect(found.id).toBe(id);
            expect(found.tenantId).toBe(tenant.id);
            expect(found.name).toBe(result.agency.name);
            expect(found.code).toBe(result.agency.code);
            expect(found.agencyType).toBe(result.agency.agencyType);
            expect(found.active).toBe(true);
          }

          // Inv 3: deactivate the first successfully created agency if requested
          const firstId = createdIds[0];
          if (firstId !== undefined && deactivateFirst) {
            const deactivated = await store.setAgencyActive(firstId, false);
            expect(deactivated).not.toBeNull();
            const readBack = await store.findAgencyById(firstId);
            expect(readBack?.active).toBe(false);
          }

          // Inv 4: agency coverage roundtrip on the first created agency
          if (firstId !== undefined) {
            await store.setCoverage(firstId, coverageOffices);
            const expectedCoverage = new Set(coverageOffices);
            const actualCoverage = new Set(await store.listCoverage(firstId));
            expect(actualCoverage).toEqual(expectedCoverage);
          }
        },
      ),
      { numRuns: RUNS },
    );
  });
});
